    /// <summary>
    /// This test ensures that the CRC32 implementation works correctly across various seeds
    /// and data lengths by comparing to a simple reference implementation.
    /// </summary>
    [Fact]
    public void Hash_AllLengthsUpTo1024_MatchesReference()
    {
        byte[] buffer = new byte[1024];
        Random.Shared.NextBytes(buffer);

        uint[] testSeeds = [0, 1858192374, 1, 0x12345678, uint.MaxValue];

        foreach (uint testSeed in testSeeds)
        {
            Crc32 crc = new(testSeed);
            for (int len = 0; len <= buffer.Length; len++)
            {
                ReadOnlySpan<byte> slice = buffer.AsSpan(0, len);
                uint expected = ComputeReferenceCrc32(testSeed, slice);
                uint actual = crc.Hash(slice);
                Assert.Equal(expected, actual);
            }
        }
    }

    private static uint ComputeReferenceCrc32(uint seed, ReadOnlySpan<byte> data)
    {
        uint state = Crc32RefLookup[~seed & 0xFF];
        state ^= 0x00FFFFFF;
        uint index = (seed >> 8) ^ state;
        state = (state >> 8) & 0x00FFFFFF;
        state ^= Crc32RefLookup[index & 0xFF];
        index = (seed >> 16) ^ state;
        state = (state >> 8) & 0x00FFFFFF;
        state ^= Crc32RefLookup[index & 0xFF];
        index = (seed >> 24) ^ state;
        state = (state >> 8) & 0x00FFFFFF;
        state ^= Crc32RefLookup[index & 0xFF];

        uint crc = state;
        foreach (byte b in data)
            crc = (crc >> 8) ^ Crc32RefLookup[(crc & 0xFF) ^ b];

        return ~crc;
    }

